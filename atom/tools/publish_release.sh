#!/bin/sh
# Publish an immutable signed package first, then atomically advance latest.json.
# Usage: atom/tools/publish_release.sh DIR [user@host]
set -eu
DIR=$1; HOST=${2:-root@47.102.197.71}; KEY=${ATOM_SSH_KEY:-$HOME/.ssh/ldcx_ed25519}
VERSION=$(python3 - "$DIR" <<'PY'
import hashlib,json,re,sys
from pathlib import Path
p=Path(sys.argv[1]);m=json.loads((p/'latest.json').read_text())
v=m['version']
if not isinstance(v,str) or not re.fullmatch(r'[0-9]+(?:\.[0-9]+){1,4}',v) or len(v)>40: raise SystemExit('Invalid version')
b=(p/(v+'.tar.gz')).read_bytes()
if len(b)!=m['size'] or hashlib.sha256(b).hexdigest()!=m['sha256']: raise SystemExit('Package checksum mismatch')
print(v)
PY
)
STAGE=$(ssh -i "$KEY" -o BatchMode=yes "$HOST" 'mktemp -d /var/tmp/atom-release.XXXXXXXX')
# STAGE is generated by mktemp, never derived from manifest or user input.
case "$STAGE" in /var/tmp/atom-release.*) ;; *) exit 1 ;; esac
trap 'ssh -i "$KEY" -o BatchMode=yes "$HOST" "rm -rf -- $STAGE" >/dev/null 2>&1 || true' EXIT HUP INT TERM
scp -q -i "$KEY" -o BatchMode=yes "$DIR/$VERSION.tar.gz" "$DIR/latest.json" "$HOST:$STAGE/"
ssh -i "$KEY" -o BatchMode=yes "$HOST" python3 - "$STAGE" <<'PY'
import hashlib,json,os,pwd,re,sys
from pathlib import Path
stage=Path(sys.argv[1]);m=json.loads((stage/'latest.json').read_text());v=m['version']
if not re.fullmatch(r'[0-9]+(?:\.[0-9]+){1,4}',v): raise SystemExit('Invalid version')
package=stage/(v+'.tar.gz');payload=package.read_bytes()
if len(payload)!=m['size'] or hashlib.sha256(payload).hexdigest()!=m['sha256']: raise SystemExit('Upload verification failed')
root=Path('/var/lib/atom/system');root.mkdir(mode=0o700,parents=True,exist_ok=True)
owner=pwd.getpwnam('atom');os.chown(str(root),owner.pw_uid,owner.pw_gid)
target=root/package.name
if target.exists() and hashlib.sha256(target.read_bytes()).hexdigest()!=m['sha256']:
    raise SystemExit('This version already exists with different contents; increment VERSION')
for source,destination in [(package,target),(stage/'latest.json',root/'latest.json')]:
    os.chmod(str(source),0o600);os.chown(str(source),owner.pw_uid,owner.pw_gid)
    with source.open('rb') as stream: os.fsync(stream.fileno())
    source.replace(destination)
    fd=os.open(str(root),os.O_RDONLY)
    try: os.fsync(fd)
    finally: os.close(fd)
print('Published '+v)
PY
