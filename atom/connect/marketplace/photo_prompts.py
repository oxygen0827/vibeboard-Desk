def build_prompt(prompt, style, reference=False):
    """Keep explicit edits authoritative; no invented coordinates or keyword piles."""
    task = prompt.strip() or ('将参考照片转换为所选视觉风格。' if reference else '创作一张主体明确、构图简洁的画面。')
    parts = [task]
    if STYLES[style][1]:
        parts.append('视觉风格：' + STYLES[style][1] + ' 若与上述明确要求冲突，以上述要求为准。')
    if reference:
        parts.append('依据参考照片编辑，保留未要求修改的主体特征、内容和构图；不要擅自增加人物或物品。')
    parts.append('输出一张完整图片；画面文字仅按明确要求生成。')
    return '\n'.join(parts)
